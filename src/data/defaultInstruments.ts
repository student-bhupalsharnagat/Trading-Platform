import { Instrument } from '../types.ts';

function makeEquityShare(
  id: string,
  symbol: string,
  name: string,
  price: number,
  change: number,
  changePercent: number,
  intradayMargin: number,
  holdingMargin: number,
  sparkline: number[],
  trend: 'up' | 'down' = change >= 0 ? 'up' : 'down'
): Instrument {
  const spread = Number((price * 0.0003).toFixed(2));
  const open = Number((price - change).toFixed(2));
  return {
    id,
    symbol,
    name,
    sectionName: 'NSE EQ',
    category: 'EQUITY',
    expiry: 'NSE EQ',
    lastPrice: price,
    openPrice: open,
    highPrice: Number((Math.max(price, open) * 1.012).toFixed(2)),
    lowPrice: Number((Math.min(price, open) * 0.988).toFixed(2)),
    prevClose: open,
    change,
    changePercent,
    intraday: intradayMargin,
    holding: holdingMargin,
    lotSize: 1,
    maxLots: 1000,
    ask: Number((price + (spread || 0.05)).toFixed(2)),
    bid: Number((price - (spread || 0.05)).toFixed(2)),
    sparkline,
    trend,
  };
}

